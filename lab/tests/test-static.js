'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8'),app=fs.readFileSync(path.join(root,'js/app.js'),'utf8'),css=fs.readFileSync(path.join(root,'css/style.css'),'utf8');
const ids=[...html.matchAll(/\sid=["']([^"']+)["']/g)].map(m=>m[1]);
assert.strictEqual(new Set(ids).size,ids.length,'Existem IDs duplicados no index.html.');
const refs=[...html.matchAll(/<(?:script|link|img)\b[^>]*(?:src|href)=["']([^"']+)["']/gi)].map(m=>m[1]).filter(v=>! /^(?:https?:|data:|#)/.test(v));
const missing=refs.filter(ref=>!fs.existsSync(path.join(root,ref.split('?')[0])));
assert.deepStrictEqual(missing,[],'Existem referências locais ausentes.');
assert.ok(/Content-Security-Policy/.test(html),'CSP ausente.');
assert.ok(/id=["']studentDialog["']/.test(html),'Modal de identificação ausente.');
assert.ok(/id=["']historyDialog["']/.test(html),'Histórico de sessão ausente.');
assert.ok(/data-session-export=["']zip["']/.test(html),'Exportação ZIP ausente.');
assert.ok(/id=["']toolResultCount["']/.test(html),'Contador acessível dos filtros ausente.');
assert.ok(/role=["']tab["'][^>]+aria-selected/.test(html),'Filtros de categoria sem estado acessível.');
assert.ok(/normalize\('NFD'\)/.test(app),'Busca não normaliza termos com e sem acento.');
for(const theme of ['cmd','powershell','bash','ubuntu','debian','kali','fedora','macos','chromeos'])assert.ok(css.includes(`body[data-terminal-theme="${theme}"]`),`Identidade visual ausente: ${theme}`);
console.log(`✓ ${ids.length} IDs únicos e ${refs.length} referências locais válidas.`);
console.log('✓ CSP, identificação, histórico e exportação completa presentes.');
console.log('✓ Busca sem acento, contador e filtros acessíveis presentes.');
console.log('✓ Identidades visuais específicas dos nove terminais presentes.');
