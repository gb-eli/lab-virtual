'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const context={window:{},globalThis:{},crypto:require('crypto').webcrypto,setTimeout,clearTimeout,AbortController,performance:require('perf_hooks').performance,console};
context.globalThis=context;
vm.createContext(context);
for(const file of ['js/labs/vm/profiles.js','js/labs/vm/engine.js','js/labs/vm/renderer.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context,{filename:file});
const profiles=context.window.LABDS_VM_PROFILES;
const Engine=context.window.LABDS_VM_ENGINE.VMEngine;
assert.ok(Object.keys(profiles).length>=15,'Poucos perfis de sistemas operacionais.');
for(const id of ['windows7','windows8','windows81','windows10','ubuntu2404','mint','debian13','fedora','arch','chromeos','chromeos-flex','mac-intel','mac-apple'])assert.ok(profiles[id],`Perfil ausente: ${id}`);
let engine=new Engine({profiles,initial:{profileId:'windows10',ramGB:4,diskGB:80,arch:'x64',firmware:'uefi',partitionTable:'gpt',secureBoot:true,tpm:'2.0',media:{type:'iso',label:'Windows 10',architecture:'x64',integrity:'valid',inserted:true}}});
assert.strictEqual(engine.validation().ok,true,'Windows 10 compatível foi bloqueado.');
engine.setAutomaticPartitions();
assert.ok(engine.state.partitions.some(p=>p.filesystem==='ntfs'),'Partição NTFS não criada.');
assert.ok(engine.state.partitions.some(p=>p.type==='efi'),'Partição EFI não criada.');
engine.selectProfile('ubuntu2404');
engine.updateConfig({ramGB:8,diskGB:80,arch:'x64',firmware:'uefi',partitionTable:'gpt',secureBoot:true,media:{type:'iso',label:'Ubuntu',architecture:'x64',integrity:'valid',inserted:true}});
engine.setAutomaticPartitions();
assert.ok(engine.state.partitions.some(p=>p.mount==='/'),'Partição raiz Linux não criada.');
assert.ok(engine.state.partitions.some(p=>p.mount==='/boot/efi'),'EFI Linux não criada.');
engine.selectProfile('windows11');
engine.updateConfig({ramGB:8,diskGB:128,arch:'x64',firmware:'uefi',secureBoot:false,tpm:'2.0',media:{type:'iso',label:'Windows 11',architecture:'x64',integrity:'valid',inserted:true}});
assert.ok(engine.validation().issues.some(x=>/Secure Boot/.test(x)),'Windows 11 deveria exigir Secure Boot.');
engine.selectProfile('chromeos-flex');
engine.updateConfig({arch:'arm64',ramGB:8,diskGB:64,firmware:'uefi',media:{type:'usb',label:'ChromeOS Flex',architecture:'arm64',integrity:'valid',inserted:true}});
assert.strictEqual(engine.validation().ok,false,'ChromeOS Flex ARM foi aceito incorretamente.');
engine.selectProfile('mac-apple');
assert.strictEqual(engine.profile().defaultArch,'arm64');
assert.ok(engine.profile().firmwareSupport.includes('mac-apple'));
engine.checkpoint('Teste');
const cp=engine.state.checkpoints[0];engine.updateConfig({ramGB:32});engine.restoreCheckpoint(cp.id);assert.notStrictEqual(engine.state.ramGB,32,'Checkpoint não restaurou estado.');
engine.setState('installer_copying');
assert.throws(()=>engine.checkpoint('Inválido'),/operação atual/,'Checkpoint transitório deveria ser bloqueado.');
engine.setState('powered_off');
engine.updateConfig({installed:true,selectedBoot:'disk',media:{...engine.state.media,inserted:false}});
assert.strictEqual(engine.validation().ok,true,'Sistema instalado deveria iniciar sem ISO conectada.');
engine.selectBoot('media');
assert.strictEqual(engine.state.errorCode,'NO_BOOTABLE_MEDIA','Boot pela mídia ausente deveria gerar erro específico.');
engine.setState('powered_off');
engine.updateConfig({installed:false,media:{...engine.state.media,inserted:false}});
assert.strictEqual(engine.validation().ok,false,'Máquina sem sistema e sem mídia não deveria inicializar.');
engine.updateConfig({media:{...engine.state.media,inserted:true,integrity:'valid'},powerState:'installer_copying',progress:47,installStep:2,lastInstallDetail:'Copiando arquivos do sistema'});
const screen=context.window.LABDS_VM_RENDERER.render(engine.profile(),engine.state,engine.validation());
assert.ok(screen.includes('install-checklist'),'Tela de instalação detalhada ausente.');
assert.ok(screen.includes('aria-valuenow="47"'),'Progresso acessível não refletiu o estado.');
const report=engine.report();assert.strictEqual(report.passwordContentStored,false,'Relatório não pode armazenar senha.');
console.log(`✓ ${Object.keys(profiles).length} perfis de SO validados.`);
console.log('✓ Requisitos, partições, checkpoints e privacidade da VM aprovados.');
console.log('✓ Bloqueio de checkpoints transitórios e boot sem ISO após instalação aprovados.');
console.log('✓ Renderização detalhada e progresso acessível da instalação aprovados.');
